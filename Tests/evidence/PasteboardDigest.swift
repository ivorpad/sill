// What is on a pasteboard, without its contents (Tests/evidence/README.md): each item's types, and per
// type the byte count and SHA-256, plus which of Sill's private markers (ClipboardItem.privateTypes,
// Sources/StreamProtocol/Clipboard.swift, compiled in beside this file) are present. Shared by the
// pasteboard and macstate tools. Never prints or keeps a byte of the contents.
import AppKit
import CryptoKit

enum PasteboardDigest {
    static func hex(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    /// changeCount, the items with per-type size and hash, and the markers present.
    static func read(_ pb: NSPasteboard = .general) -> [String: Any] {
        var items: [[String: Any]] = []
        var allTypes = Set<String>()
        for (index, item) in (pb.pasteboardItems ?? []).enumerated() {
            var types: [[String: Any]] = []
            for type in item.types {
                allTypes.insert(type.rawValue)
                if let data = item.data(forType: type) {
                    types.append(["type": type.rawValue, "bytes": data.count, "sha256": hex(data)])
                } else {
                    types.append(["type": type.rawValue, "bytes": NSNull(), "sha256": NSNull()])
                }
            }
            items.append(["index": index, "types": types])
        }
        let marker = { (name: String) in allTypes.contains(name) }
        return [
            "changeCount": pb.changeCount,
            "items": items,
            "concealed": marker("org.nspasteboard.ConcealedType"),
            "transient": marker("org.nspasteboard.TransientType"),
            "autoGenerated": marker("org.nspasteboard.AutoGeneratedType"),
            "privateTypesPresent": ClipboardItem.privateTypes.filter(marker).sorted(),
            "sillSkips": ClipboardItem.skips(types: Array(allTypes)),
        ]
    }
}
