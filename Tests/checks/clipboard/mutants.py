"""The shared clipboard's rules (Sources/StreamProtocol/Clipboard.swift): each mutant changes the file in one place
and must fail the check (main.swift). usage: mutants.py"""
import os, subprocess, sys
SP = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(SP, "..", "..", ".."))   # the repository
OUT = os.path.join(ROOT, ".build", "checks", "clipboard")   # the mutants' sources and binaries
os.makedirs(OUT, exist_ok=True)
SRC = os.path.join(ROOT, "Sources/StreamProtocol/Clipboard.swift")
orig = open(SRC).read()
RULE = "share && (shareAway || !away)"
CHOICE = "return firstList && sharedLastSession ? .send : .startOver"
MUTANTS = {
    # The echo rule (ClipboardEcho)
    "M1 the change-count comparison off by one": ("return count != seen", "return count - seen > 1"),
    "M2 the side's own write not remembered": ("    public mutating func wrote(_ count: Int) {\n        seen = count\n    }",
                                               "    public mutating func wrote(_ count: Int) {\n    }"),
    "M3 the copy from before the session sent": ("guard let seen else { return false }", "guard let seen else { return true }"),
    # What stays on the Mac
    "M4 the concealed filter dropped": ('        "org.nspasteboard.ConcealedType",\n', ""),
    "M5 the transient filter dropped": ('        "org.nspasteboard.TransientType",\n', ""),
    "M6 the auto-generated filter dropped": ('        "org.nspasteboard.AutoGeneratedType",\n', ""),
    "M7 the cap's edge left out": ("return size <= (toHost ?", "return size < (toHost ?"),
    # Who shares (ClipboardPolicy)
    "M8 the away gate dropped": (RULE, "share"),
    "M9 the away switch shares by itself": (RULE, "(share || shareAway) && (shareAway || !away)"),
    "M10 the home switch ignored": (RULE, "shareAway || !away"),
    "M11 the generation advertised to every connection": ("shares(away: away) ? ClipboardItem.generation : nil", "ClipboardItem.generation"),
    "M12 watching only while every device shares": ("devicesAway.contains { shares(away: $0) }", "devicesAway.allSatisfy { shares(away: $0) }"),
    # The enable moment on the Mac (ClipboardWatch)
    "M13 the count at the enable moment not taken": ("        if on { _ = echo.looked(at: count) }\n", ""),
    "M14 sent while sharing is off": ("        guard on else { return false }\n        return echo.looked(at: count)", "        return echo.looked(at: count)"),
    # The enable moment on the device (ClipboardListAction)
    "M15 the copy from before the Mac shared sent mid-session": (CHOICE, "return .send"),
    "M16 the last session's sharing ignored": (CHOICE, "return firstList ? .send : .startOver"),
    "M17 a list that changes nothing acts": ("guard takes, !took else { return .nothing }", "guard takes else { return .nothing }"),
    "M18 the generation's edge left out": ("let takes = (now ?? 0) >= ClipboardItem.generation", "let takes = (now ?? 0) > ClipboardItem.generation"),
    # Two minutes (ClipboardExpiry)
    "M19 the expiry compare inverted": ("return now - at >= Self.lifetime", "return now - at < Self.lifetime"),
    "M20 the expiry's edge left out": ("return now - at >= Self.lifetime", "return now - at > Self.lifetime"),
    "M21 cleared whatever was copied since": ("guard let count, current == count else { return false }", "guard count != nil else { return false }"),
    "M22 one minute": ("public static let lifetime: Double = 120", "public static let lifetime: Double = 60"),
}
caught = 0
for name, (old, new) in MUTANTS.items():
    if orig.count(old) != 1:
        print(f"{name}: NOT APPLIED (pattern found {orig.count(old)} times)"); continue
    path = os.path.join(OUT, "mutant.swift")
    open(path, "w").write(orig.replace(old, new))
    b = subprocess.run(["swiftc", "-O", path, os.path.join(SP, "main.swift"), "-o", os.path.join(OUT, "mutant")],
                       capture_output=True, text=True)
    if b.returncode != 0:
        print(f"{name}: DOES NOT COMPILE\n{b.stderr[:600]}"); continue
    r = subprocess.run([os.path.join(OUT, "mutant")], capture_output=True, text=True, timeout=300)
    failed = [l[5:] for l in r.stdout.splitlines() if l.startswith("FAIL")]
    ok = r.returncode != 0
    caught += ok
    print(f"{'caught' if ok else 'MISSED'} {name}: {len(failed)} failing, e.g. {[f[:100] for f in failed[:2]]}")
print(f"{caught} of {len(MUTANTS)} mutants caught")
sys.exit(0 if caught == len(MUTANTS) else 1)
