import Foundation

// ClipboardItem and ClipboardEcho (Sources/StreamProtocol/Clipboard.swift), compiled on their own:
//   swiftc -O Sources/StreamProtocol/Clipboard.swift Tests/checks/clipboard/main.swift -o check
var failures = 0, checks = 0
func check(_ ok: Bool, _ what: @autoclosure () -> String, line: Int = #line) {
    checks += 1
    if !ok { failures += 1; print("FAIL (line \(line)): \(what())") }
}
typealias C = ClipboardItem

// MARK: What is sent

check(C(text: "hello").fits(toHost: true) && C(text: "hello").fits(toHost: false), "text goes both ways")
check(!C(text: "").fits(toHost: true), "empty text is nothing to send")
check(C(image: Data(repeating: 1, count: 1000), type: "png").fits(toHost: true), "a small PNG goes")
check(C(image: Data(repeating: 1, count: 1000), type: "jpeg").fits(toHost: true), "a small JPEG goes")
check(!C(image: Data(repeating: 1, count: 1000), type: "gif").fits(toHost: true), "another image type does not")
check(!C(image: Data(), type: "png").fits(toHost: true), "an empty image does not")
var both = C(text: "a"); both.image = Data([1]); both.imageType = "png"
check(!both.fits(toHost: true), "text and an image together: not an item")
var neither = C(text: "a"); neither.text = nil
check(!neither.fits(toHost: true), "neither: not an item")
// The caps, at and over, each way; text counts its UTF-8 bytes.
check(C(image: Data(count: C.maxToHostBytes), type: "png").fits(toHost: true), "at the device's cap: goes")
check(!C(image: Data(count: C.maxToHostBytes + 1), type: "png").fits(toHost: true), "over the device's cap: does not")
check(C(image: Data(count: C.maxToHostBytes + 1), type: "png").fits(toHost: false), "the Mac's cap is larger")
check(!C(image: Data(count: C.maxToDeviceBytes + 1), type: "png").fits(toHost: false), "over the Mac's cap: does not")
check(C(text: "é").size == 2, "text counts UTF-8 bytes")
check(!C(text: String(repeating: "é", count: C.maxToHostBytes / 2 + 1)).fits(toHost: true), "long text over the device's cap")
// Each cap leaves room for base64 and the JSON around it inside the message limit it travels under
// (StreamMessage.maxClientPayload 1 MiB, maxOtherHostPayload 4 MiB).
let toHost = try! JSONEncoder().encode(C(image: Data(count: C.maxToHostBytes), type: "jpeg"))
let toDevice = try! JSONEncoder().encode(C(image: Data(count: C.maxToDeviceBytes), type: "jpeg"))
check(toHost.count < 1 << 20, "the device's largest item fits a client message (\(toHost.count))")
check(toDevice.count < 4 << 20, "the Mac's largest item fits a host message (\(toDevice.count))")

// MARK: What stays on the Mac

check(C.skips(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]), "a concealed copy stays")
check(C.skips(types: ["org.nspasteboard.TransientType"]), "a transient copy stays")
check(C.skips(types: ["org.nspasteboard.AutoGeneratedType", "public.png"]), "an auto-generated copy stays")
check(C.skips(types: ["com.agilebits.onepassword", "public.utf8-plain-text"]), "1Password 7's copy stays")
check(!C.skips(types: ["public.utf8-plain-text", "public.html"]), "plain text goes")
check(!C.skips(types: []), "no types: nothing to keep back")

// MARK: The wire

let text = try! JSONEncoder().encode(C(text: "hi"))
check(String(data: text, encoding: .utf8) == #"{"text":"hi"}"#, "text on the wire: \(String(data: text, encoding: .utf8)!)")
let image = try! JSONEncoder().encode(C(image: Data([0, 1, 2]), type: "png"))
check(try! JSONDecoder().decode(C.self, from: image) == C(image: Data([0, 1, 2]), type: "png"), "an image round-trips")
check((try? JSONDecoder().decode(C.self, from: Data(#"{"text":"x","later":1}"#.utf8))) == C(text: "x"), "a later field is ignored")
check((try? JSONDecoder().decode(C.self, from: Data("{}".utf8)))?.fits(toHost: true) == false, "an empty object decodes to nothing to use")

// MARK: The echo rule

var e = ClipboardEcho()
check(!e.looked(at: 5), "the first look only remembers: what was there before is not sent")
check(!e.looked(at: 5), "no change: nothing")
check(e.looked(at: 6), "a new copy here: sent")
check(!e.looked(at: 6), "and only once")
e.wrote(7)
check(!e.looked(at: 7), "what the other side wrote is not sent back")
check(e.looked(at: 8), "the next copy here is")
// Counts that jump (several copies between looks) or go down (a reboot of the pasteboard server) are
// still one new copy.
check(e.looked(at: 20), "a jump: one copy")
check(e.looked(at: 3), "a count that went down: a copy too")
// 5,000 random sessions against a model: a side's own copies are sent exactly when the count it
// sees differs from the last count it saw or wrote.
var rng = SystemRandomNumberGenerator()
var held = 0
for _ in 0..<5_000 {
    var echo = ClipboardEcho(), count = Int.random(in: 0...100, using: &rng), last: Int? = nil, ok = true
    for _ in 0..<40 {
        switch Int.random(in: 0..<4, using: &rng) {
        case 0: count += 1                                          // a copy on this side
        case 1: count += 1; echo.wrote(count); last = count         // the other side's copy, written here
        default:
            let expected = last.map { $0 != count } ?? false
            if echo.looked(at: count) != expected { ok = false }
            last = count
        }
    }
    if ok { held += 1 }
}
check(held == 5_000, "random sessions match the model (\(held) of 5000)")

print(failures == 0 ? "ok: \(checks) checks" : "FAIL: \(failures) of \(checks) checks")
exit(failures == 0 ? 0 : 1)
