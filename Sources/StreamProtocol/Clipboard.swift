import Foundation

/// Kind 29, both ways: what was just copied on one side, for the other's clipboard. Text, or one
/// image (PNG or JPEG bytes), never both. A side sends only its own copies: what the other side put
/// on its clipboard is not sent back (`ClipboardEcho`).
///
/// The device sends kind 29 only to a host whose window list says `clipboard` 1 or more
/// (`WindowList.clipboard`); an older device skips the kind. On the Mac, what an app marks as
/// concealed or transient (a password manager's copy) is never sent (`ClipboardItem.skips`).
public struct ClipboardItem: Codable, Equatable {
    public var text: String?
    public var image: Data?
    /// "png" or "jpeg", with `image`.
    public var imageType: String?

    public init(text: String) { self.text = text }
    public init(image: Data, type: String) { self.image = image; imageType = type }

    /// The generation `WindowList.clipboard` says: 1 is text and one image, both ways.
    public static let generation = 1

    /// The largest item a device sends: the client payload is capped at 1 MiB
    /// (`StreamMessage.maxClientPayload`), and JSON carries an image in base64, a third larger.
    public static let maxToHostBytes = 700_000
    /// The largest item the Mac sends, under `StreamMessage.maxOtherHostPayload` (4 MiB) the same way.
    public static let maxToDeviceBytes = 2_800_000

    /// The size that counts against the caps: the text's UTF-8 or the image's bytes.
    public var size: Int { (text?.utf8.count ?? 0) + (image?.count ?? 0) }

    /// Whether it is something to send at all, and small enough for that direction.
    public func fits(toHost: Bool) -> Bool {
        let hasText = !(text ?? "").isEmpty
        let hasImage = !(image ?? Data()).isEmpty && (imageType == "png" || imageType == "jpeg")
        guard hasText != hasImage else { return false }      // exactly one of the two
        return size <= (toHost ? Self.maxToHostBytes : Self.maxToDeviceBytes)
    }

    /// The pasteboard types (nspasteboard.org's markers) whose copies stay on the Mac: a password
    /// manager's concealed copy, a transient one, and one an app made by itself.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",            // 1Password 7 marks its copies with this as well
    ]

    /// Whether a copy whose pasteboard holds `types` stays on its side.
    public static func skips(types: [String]) -> Bool {
        types.contains { privateTypes.contains($0) }
    }
}

/// One side's memory of its clipboard's change count, so it sends each of its own copies once and
/// never sends back what the other side gave it. A clipboard's change count goes up by one with
/// every write, its own included (NSPasteboard and UIPasteboard alike).
public struct ClipboardEcho: Equatable {
    /// The count last looked at, nil before the first look (whatever is on the clipboard then was
    /// copied before the session: it is not sent).
    public private(set) var seen: Int?

    public init() {}

    /// The clipboard reads `count` now: true when that is a new copy made on this side, to send.
    /// The first look only remembers.
    public mutating func looked(at count: Int) -> Bool {
        defer { seen = count }
        guard let seen else { return false }
        return count != seen
    }

    /// This side just wrote what the other side sent, and the clipboard now reads `count`: that
    /// count is not a copy of this side's, so it is not sent back.
    public mutating func wrote(_ count: Int) {
        seen = count
    }
}
